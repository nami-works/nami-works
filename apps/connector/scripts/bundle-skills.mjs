// Bundles curated Claude Code skills into a committed TS module the connector
// serves at runtime (the brand_* skill tools). Source of truth stays the
// canonical `.claude/skills/**` + referenced docs; those live outside the Docker
// build context (.dockerignore excludes `.claude` and `docs`), so we generate an
// in-`src` module on the host and commit it — a rebuild ships the current copy.
//
// Regenerate after editing a served skill or its playbook:
//   node apps/connector/scripts/bundle-skills.mjs
//
// To serve another skill to the team: add an entry to MANIFEST and rerun.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// scripts/ -> connector -> apps -> repo root
const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");

const MANIFEST = [
  {
    name: "creative-producer",
    title: "Conteúdo · Produtor de criativos",
    skill: ".claude/skills/creative-producer/SKILL.md",
    // Referenced knowledge the skill tells the reader to consult — inlined so a
    // connector user gets the full depth without repo access.
    references: ["docs/creative-ad-image-pipeline.md"],
  },
];

function stripFrontmatter(md) {
  const m = /^---\n[\s\S]*?\n---\n?/.exec(md);
  return m ? md.slice(m[0].length).replace(/^\s+/, "") : md;
}

const skills = {};
for (const entry of MANIFEST) {
  const body = stripFrontmatter(readFileSync(resolve(repoRoot, entry.skill), "utf8").trim());
  let content = body;
  for (const ref of entry.references) {
    const refText = readFileSync(resolve(repoRoot, ref), "utf8").trim();
    content += `\n\n---\n\n# CANONICAL PLAYBOOK — ${ref}\n\n${refText}`;
  }
  skills[entry.name] = { title: entry.title, content };
}

const banner =
  "// AUTO-GENERATED by apps/connector/scripts/bundle-skills.mjs — do not edit by hand.\n" +
  "// Regenerate after editing a served skill or playbook:\n" +
  "//   node apps/connector/scripts/bundle-skills.mjs\n\n";
const out =
  banner +
  "export type ServedSkill = { title: string; content: string };\n\n" +
  `export const SERVED_SKILLS: Record<string, ServedSkill> = ${JSON.stringify(skills, null, 2)};\n`;

const dest = resolve(repoRoot, "apps/connector/src/generated/served-skills.ts");
mkdirSync(dirname(dest), { recursive: true });
writeFileSync(dest, out);
// eslint-disable-next-line no-undef -- Node build script, run manually via node
console.log(
  `wrote ${dest}\nserved skills: ${Object.entries(skills).map(([k, v]) => `${k} (${v.content.length} chars)`).join(", ")}`,
);
