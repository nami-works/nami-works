// Bundles gebeauty/products.json + gebeauty/category-taxonomy.json into a
// committed TS module the connector reads at runtime (shopify_generate_
// marketplace_registry and friends). Source of truth stays gebeauty/**, which
// lives outside the Docker build context (.dockerignore excludes it, and the
// Dockerfile's build context only copies apps/connector + prisma) — same
// problem bundle-skills.mjs already solved for skills, same fix here.
//
// Regenerate after editing products.json or category-taxonomy.json:
//   node apps/connector/scripts/bundle-catalog.mjs

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// scripts/ -> connector -> apps -> repo root
const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");

const products = JSON.parse(
  readFileSync(resolve(repoRoot, "gebeauty/products.json"), "utf8"),
);
const taxonomy = JSON.parse(
  readFileSync(resolve(repoRoot, "gebeauty/category-taxonomy.json"), "utf8"),
);

const banner =
  "// AUTO-GENERATED by apps/connector/scripts/bundle-catalog.mjs — do not edit by hand.\n" +
  "// Regenerate after editing gebeauty/products.json or gebeauty/category-taxonomy.json:\n" +
  "//   node apps/connector/scripts/bundle-catalog.mjs\n\n";
const out =
  banner +
  `export const PRODUCTS = ${JSON.stringify(products, null, 2)} as const;\n\n` +
  `export const CATEGORY_TAXONOMY = ${JSON.stringify(taxonomy, null, 2)} as const;\n`;

const dest = resolve(repoRoot, "apps/connector/src/generated/catalog-data.ts");
mkdirSync(dirname(dest), { recursive: true });
writeFileSync(dest, out);
// eslint-disable-next-line no-undef -- Node build script, run manually via node
console.log(`wrote ${dest}\n${products.length} SKUs, ${taxonomy.canonical_categories.length} canonical categories`);
